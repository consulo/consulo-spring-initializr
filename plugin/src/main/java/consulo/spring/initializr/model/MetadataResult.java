package consulo.spring.initializr.model;

import org.jspecify.annotations.Nullable;

import java.util.List;

/**
 * The bundled {@code spring-initializr-metadata.json}, generated by {@code update-metadata.py}.
 */
public record MetadataResult(List<MetadataItem> bootVersions,
                             List<MetadataItem> javaVersions,
                             List<MetadataItem> languages,
                             List<MetadataItem> types,
                             List<MetadataItem> packagings,
                             List<DependencyGroupItem> dependencies) {
    public MetadataResult {
        bootVersions = orEmpty(bootVersions);
        javaVersions = orEmpty(javaVersions);
        languages = orEmpty(languages);
        types = orEmpty(types);
        packagings = orEmpty(packagings);
        dependencies = orEmpty(dependencies);
    }

    private static <T> List<T> orEmpty(@Nullable List<T> list) {
        return list == null ? List.of() : list;
    }
}
